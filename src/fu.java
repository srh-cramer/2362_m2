void main() {

    // Arrays anlegen, Langvariante:
    //
    // Ein leeres int Array anlegen der Länge 5
    int[] zahlen = new int[5];
    // An erster Stelle die Zahl 20 platzieren
    zahlen[0] = 20;
    zahlen[1] = 40;
    zahlen[2] = 60;
    zahlen[3] = 80;
    zahlen[4] = 100;

    // Arrays anlegen, Kurzvariante:
    //
    // Array direkt mit Werten anlegen:
    int[] kurzeZahlen = {20, 40, 60, 80, 100};
    // Inhalte überschreiben:
    kurzeZahlen[0] = 150;


}